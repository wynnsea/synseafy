function makeWaveform(seed: number, length = 42): number[] {
  const bars: number[] = [];
  for (let i = 0; i < length; i++) {
    const wave =
      Math.sin((i + seed) * 0.45) * 0.3 +
      Math.cos((i * 1.7 + seed) * 0.35) * 0.25 +
      0.5;
    const envelope = Math.sin((i / (length - 1)) * Math.PI);
    const val = Math.max(0.18, Math.min(1, wave * (0.45 + envelope * 0.65)));
    bars.push(Number(val.toFixed(2)));
  }
  return bars;
}

